dia_semana = int(input("insira um numero de 1 a 7: "))

match dia_semana:
    case 1:
        print("domingo")
    case 2:
        print("segunda")
    case 3:
        print("terca")
    case 4:
        print("quarta")
    case 5:
        print("quinta")
    case 6:
        print("sexta")
    case 7:
        print("sabado")
    case _:
        print("numero invalido")
        

            
